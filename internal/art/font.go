// Glyph is a rasterised character: a white mask plus its advance.
type Glyph struct {
	C       *Canvas
	Advance int
}

// Glyphs rasterises the whole font.
func Glyphs() map[rune]Glyph {
	out := map[rune]Glyph{}
	for r, data := range glyphData {
		var rows []string
		if strings.Contains(data, "/") {
			rows = strings.Split(data, "/")
		} else {
			for _, ch := range data {
				rows = append(rows, string(ch))
			}
		}
		w := 0
		for _, row := range rows {
			for i, ch := range row {
				if ch == '#' && i+1 > w {
					w = i + 1
				}
			}
		}
		if w == 0 {
			w = 1
		}
		c := NewCanvas(w, FontHeight)
		for y, row := range rows {
			for x, ch := range row {
				if ch == '#' {
					c.Set(x, y, White)
				}
			}
		}
		out[r] = Glyph{C: c, Advance: w + 1}
	}
	return out
}
